// Generates infra/chain.json out of contracts/script/Addresses.sol.
//
// Not retyped, because packages/shared/addresses.ts has already drifted from
// Addresses.sol once. It carries four tokens where the contract carries five,
// and its GME pool is a different address. Addresses.sol is what the deploy runs
// on, so it is the source here.

import {readFileSync, writeFileSync} from "node:fs";

const [source, target] = process.argv.slice(2);
const src = readFileSync(source, "utf8");

const constants = new Map();
for (const m of src.matchAll(/constant\s+([A-Z0-9_]+)\s*=\s*(0x[0-9a-fA-F]{40})\s*;/g)) {
  constants.set(m[1], m[2]);
}

const pick = (name) => {
  const value = constants.get(name);
  if (!value) throw new Error(`not found in Addresses.sol: ${name}`);
  return value;
};

const symbols = ["NVDA", "AAPL", "TSLA", "GOOGL", "GME"];
const out = {
  _source:
    "generated by infra/scripts/extract-addresses.mjs from contracts/script/Addresses.sol. do not edit.",
  chainId: 4663,
  usdg: pick("USDG"),
  usdgDecimals: 6,
  permit2: pick("PERMIT2"),
  tokens: Object.fromEntries(
    symbols.map((s) => [
      s,
      {token: pick(s), pool: pick(`POOL_${s}`), feed: pick(`FEED_${s}`), decimals: 18},
    ]),
  ),
};

writeFileSync(target, `${JSON.stringify(out, null, 2)}\n`);
console.log(`  usdg    ${out.usdg}`);
for (const [s, v] of Object.entries(out.tokens)) {
  console.log(`  ${s.padEnd(7)} ${v.token} pool ${v.pool}`);
}
